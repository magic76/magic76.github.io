const cards=(rows:Row[],level:TabooLevel):TabooCard[]=>
 rows.map(([word,banned,clue1,clue2,keywords])=>({word,zh:word,level,banned,clues:[clue1,clue2],keywords}));
export const CHINESE_TABOO_CARDS:TabooCard[]=[...cards(easy,"easy"),...cards(medium,"medium")];
export function drawChineseTabooDeck(level:TabooLevel,random:()=>number=Math.random):TabooCard[]{
 const pool=CHINESE_TABOO_CARDS.filter(c=>c.level===level).slice();
 for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]];}
 return pool.slice(0,5);
}
