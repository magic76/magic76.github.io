 assert.match(home,/if\(!stringsReady\)throw loadUiNamespace\("lesson"\)/);
 assert.match(home,/crew-practice-friend-links/);
 assert.match(home,/crew-role-entry teacher/);
 assert.match(home,/TeacherAvatar/);
 const friendIntents=read("web-spa/src/friends/FriendIntentCards.tsx");
 assert.match(friendIntents,/crew_web_selected_friend_v1/);
 assert.match(friendIntents,/intent=share/);
